#!/usr/bin/env node
/**
 * Build clock.html: index.html, its CSS and all its JavaScript in one file,
 * so the clock can be downloaded and opened by double-clicking (browsers
 * won't load ES modules from file://).
 *
 * No dependencies. Run it after any change and before committing:
 *
 *   npm run build
 *
 * The bundler understands only the import/export forms this project uses
 * (named, default and namespace imports; export function/const/let/class,
 * export default, export { }). Anything else makes the build fail rather than
 * produce a broken file.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const jsRoot = resolve(root, "js");

export const OUTPUT = resolve(root, "clock.html");

/** The complete clock.html, as a string. */
export function buildClock() {
  const html = readFileSync(resolve(root, "index.html"), "utf8");

  const withStyles = html.replace(
    /<link rel="stylesheet" href="([^"]+)" \/>/g,
    (_, href) => `<style>\n${readFileSync(resolve(root, href), "utf8").trim()}\n    </style>`,
  );

  const scriptTag = /[ \t]*<script type="module" src="([^"]+)"><\/script>\n?/;
  const match = scriptTag.exec(withStyles);
  if (!match) throw new Error('index.html needs <script type="module" src="…"></script>');

  // The script runs at the end of <body>: a module script is deferred, but an
  // inline classic script is not, so it has to wait for the page to exist.
  const script = bundle(resolve(root, match[1])).replace(/<\/script/gi, "<\\/script");
  const withoutModule = withStyles.replace(scriptTag, "");
  if (!withoutModule.includes("</body>")) throw new Error("index.html needs a </body>");

  return withoutModule
    .replace("<!DOCTYPE html>", `<!DOCTYPE html>\n${headerComment()}`)
    .replace("</body>", `    <script>\n${script}\n    </script>\n  </body>`);
}

export const REPOSITORY = "https://github.com/rhulse/Broadcasters-Clock-v3";

/** The comment at the top of clock.html: where it came from, and the licence. */
function headerComment() {
  const license = readFileSync(resolve(root, "LICENSE"), "utf8").trim();
  // "--" would end an HTML comment early
  if (license.includes("--")) throw new Error('LICENSE contains "--", which cannot appear in an HTML comment');

  return `<!--
Broadcaster's Clock

The latest version is available at ${REPOSITORY}

This file is generated by scripts/build.mjs. Do not edit it: change the
source and run "npm run build".

${license}
-->`;
}

/** Bundle an entry module and everything it imports into one classic script. */
function bundle(entry) {
  const modules = []; // in dependency order
  const done = new Set();
  const visiting = new Set();

  function visit(file) {
    if (done.has(file)) return;
    if (visiting.has(file)) throw new Error(`Circular import involving ${moduleId(file)}`);
    visiting.add(file);

    const { code, dependencies } = transform(file, readFileSync(file, "utf8"));
    for (const dependency of dependencies) visit(dependency);

    visiting.delete(file);
    done.add(file);
    modules.push({ id: moduleId(file), code });
  }

  visit(entry);

  const body = modules
    .map(({ id, code }) => `__modules[${JSON.stringify(id)}] = (() => {\n${code}\n})();`)
    .join("\n\n");

  return `(() => {\n"use strict";\nconst __modules = {};\n\n${body}\n})();`;
}

const moduleId = (file) => relative(jsRoot, file).split(sep).join("/");

const IMPORT = /^import\s+(?:([^"';]+?)\s+from\s+)?["']([^"']+)["'];?[ \t]*$/gm;

/** Turn one ES module into the body of a function that returns its exports. */
function transform(file, source) {
  const dependencies = [];
  const exported = [];

  let code = source.replace(IMPORT, (_, clause, specifier) => {
    if (!specifier.startsWith(".")) throw new Error(`${moduleId(file)}: only relative imports are supported (${specifier})`);
    const dependency = resolve(dirname(file), specifier);
    dependencies.push(dependency);
    return clause ? bindings(clause.trim(), `__modules[${JSON.stringify(moduleId(dependency))}]`) : "";
  });

  code = code
    .replace(/^export\s+default\s+/gm, () => {
      exported.push("default: __default");
      return "const __default = ";
    })
    .replace(/^export\s+((?:async\s+)?(?:function\*?|const|let|class))\s+(\w+)/gm, (_, keyword, name) => {
      exported.push(name);
      return `${keyword} ${name}`;
    })
    .replace(/^export\s*\{([^}]*)\};?[ \t]*$/gm, (_, names) => {
      for (const item of names.split(",").map((s) => s.trim()).filter(Boolean)) {
        const [local, alias = local] = item.split(/\s+as\s+/);
        exported.push(alias === local ? local : `${alias}: ${local}`);
      }
      return "";
    });

  const leftover = /^(import|export)\b.*$/m.exec(code);
  if (leftover) throw new Error(`${moduleId(file)}: unsupported statement: ${leftover[0]}`);

  return {
    code: `${code.trim()}\n\nreturn { ${exported.join(", ")} };`,
    dependencies,
  };
}

/** The `const` declarations for one import clause. */
function bindings(clause, ref) {
  const namespace = /^\*\s+as\s+(\w+)$/.exec(clause);
  if (namespace) return `const ${namespace[1]} = ${ref};`;

  const named = /\{([^}]*)\}/.exec(clause);
  const defaultName = clause.replace(/\{[^}]*\}/, "").replace(/,/g, "").trim();

  const lines = [];
  if (defaultName) lines.push(`const ${defaultName} = ${ref}.default;`);
  if (named) {
    const names = named[1]
      .split(",")
      .map((s) => s.trim())
      .filter(Boolean)
      .map((item) => item.replace(/\s+as\s+/, ": "));
    lines.push(`const { ${names.join(", ")} } = ${ref};`);
  }
  if (!lines.length) throw new Error(`Cannot read import clause: ${clause}`);
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const html = buildClock();
  writeFileSync(OUTPUT, html);
  console.log(`Wrote ${relative(process.cwd(), OUTPUT)} (${(html.length / 1024).toFixed(1)} KB)`);
}
